#!/usr/bin/env node
// Generates .claude/rules/*.md and AGENTS.md's always-on block from the canonical .cursor/rules/*.mdc, so every agent reads the same rules.
// In the app: nothing at runtime; `pnpm rules:sync` writes, `--check` (pre-push, CI, and `pnpm check` where a project has one) fails on drift.
// Used by: package.json, .githooks/pre-push, ci.yml, and scripts/check-edited.mjs where a project wires it (after an agent edits an .mdc).
// Uses: .cursor/rules/*.mdc frontmatter (description, globs, alwaysApply); tested by scripts/sync-claude-rules.test.mjs.
//
// Why copies and not imports or symlinks: Claude Code skips `.mdc` files as non-text, in `@`
// imports and through symlinks alike, so `@.cursor/rules/core.mdc` in CLAUDE.md loads nothing.
// The .mdc stays the one file people edit; the .md is generated, and --check keeps them honest.
//
// Mapping: `agentsMd: <n>` → copied, n-th, into AGENTS.md between the markers below, and nowhere
// else: Codex, Copilot, and Cursor read AGENTS.md, and Claude imports it from CLAUDE.md. These
// rules carry no description, globs, or alwaysApply, so Cursor treats the .mdc as manual and
// doesn't load it twice. `alwaysApply: true` → no `paths` (Claude loads it at session start).
// `globs` → `paths` (loads when Claude reads a matching file). None of these → skipped: those are
// session-mode rules (showrunner, wrangler, ship, compound, farrier, dynamite-test) that load on demand as skills.
// A project's companion (`branching.project.mdc`) is just another rule: same frontmatter as the
// harness rule it extends, and with the same `agentsMd` number it sorts right after it by name.

// Node builtins only, so this runs before `pnpm install` (pre-push, a fresh clone).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// Where the canonical rules live and where Claude Code reads its copies.
const SOURCE_DIR = ".cursor/rules";
const TARGET_DIR = ".claude/rules";

// First line of every generated file; also how we recognise a file we own (and may delete).
const MARKER = "<!-- Generated by scripts/sync-claude-rules.mjs from";

// The file every agent reads, and the markers around the part of it this script owns.
const AGENTS_FILE = "AGENTS.md";
const AGENTS_BEGIN = "<!-- BEGIN always-on rules";
const AGENTS_END = "<!-- END always-on rules -->";

// Splits a Cursor `globs:` value on commas that aren't inside `{…}` (so `*.{ts,tsx}` stays whole).
// Quotes come off each glob, not just the ends, so `"e2e/**/*.ts","playwright.config.ts"` splits clean.
export const splitGlobs = (value) => {
  const globs = [];
  let depth = 0;
  let current = "";
  for (const character of value) {
    if (character === "{") depth += 1;
    if (character === "}") depth -= 1;
    if (character === "," && depth === 0) {
      globs.push(current.trim());
      current = "";
      continue;
    }
    current += character;
  }
  globs.push(current.trim());
  return globs.map((glob) => glob.replace(/^["']|["']$/g, "").trim()).filter((glob) => glob !== "");
};

// Reads the `key: value` frontmatter Cursor rules use; returns the fields and the body.
// A YAML list under a key (`globs:` then `  - src/**` lines) is joined with commas, the same
// value the one-line form gives, because Cursor accepts both and older rules use the list.
export const parseRule = (raw) => {
  // CRLF (a Windows checkout without .gitattributes) would miss the `---\n` fence, read the rule
  // as having no frontmatter, and silently drop it to a skill: its .claude/rules copy deleted, an
  // always-on rule gone from AGENTS.md, and --check agreeing. Read every rule as LF.
  const text = raw.replaceAll("\r\n", "\n");
  // No frontmatter: the whole file is the body.
  const match = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!match) return { fields: {}, body: text };
  const fields = {};
  let listKey = "";
  for (const line of (match[1] ?? "").split("\n")) {
    // A `- item` line belongs to the last key that had no inline value.
    const item = line.match(/^\s+-\s*(.*)$/);
    if (item && listKey !== "") {
      fields[listKey] = [fields[listKey], (item[1] ?? "").trim()].filter(Boolean).join(",");
      continue;
    }
    // A top-level `key: value` line; an empty value may open a list.
    const field = line.match(/^([A-Za-z]+):\s*(.*)$/);
    if (!field) continue;
    fields[field[1] ?? ""] = (field[2] ?? "").trim();
    listKey = fields[field[1] ?? ""] === "" ? (field[1] ?? "") : "";
  }
  return { fields, body: text.slice(match[0].length) };
};

// The .md Claude should see for one .mdc, or null when the rule is session-mode (a skill).
export const toClaudeRule = (name, text) => {
  const { fields, body } = parseRule(text);
  // Copied into AGENTS.md instead; Claude reads that through CLAUDE.md's `@AGENTS.md`.
  if (fields.agentsMd !== undefined) return null;
  const always = fields.alwaysApply === "true";
  const globs = splitGlobs(fields.globs ?? "");
  // Neither always-on nor scoped: loads on demand as a skill, not as a rule.
  if (!always && globs.length === 0) return null;
  // Claude reads `paths:` as a YAML list; always-on rules carry none.
  const frontmatter = [
    "---",
    `description: ${fields.description ?? name}`,
    ...(always ? [] : ["paths:", ...globs.map((glob) => `  - "${glob}"`)]),
    "---",
  ].join("\n");
  // The marker is an HTML comment, which Claude Code strips from context, so it costs nothing.
  return `${frontmatter}\n${MARKER} ${SOURCE_DIR}/${name}.mdc; edit that file, then run \`pnpm rules:sync\`. -->\n${body}`;
};

// Pushes headings one level down so a rule's `# Title` nests under AGENTS.md's; code fences untouched.
export const demoteHeadings = (body) => {
  let inFence = false;
  return body
    .split("\n")
    .map((line) => {
      // A fence line toggles; `#` inside a fence is code (a shell comment), not a heading.
      if (line.startsWith("```")) inFence = !inFence;
      return !inFence && /^#{1,5} /.test(line) ? `#${line}` : line;
    })
    .join("\n");
};

// AGENTS.md with its always-on block rebuilt from `rules` ({ name, order, body }), or appended when missing.
export const withAgentsBlock = (agents, rules) => {
  const sorted = rules.toSorted((a, b) => a.order - b.order || a.name.localeCompare(b.name));
  const sources = sorted.map((rule) => rule.name).join(",");
  const block = [
    `${AGENTS_BEGIN}: generated by scripts/sync-claude-rules.mjs from .cursor/rules/{${sources}}.mdc; edit those, then run \`pnpm rules:sync\`. -->`,
    ...sorted.map((rule) => demoteHeadings(rule.body.trim())),
    AGENTS_END,
  ].join("\n\n");
  const start = agents.indexOf(AGENTS_BEGIN);
  const end = agents.indexOf(AGENTS_END);
  // No block yet: add one at the end.
  if (start === -1 || end === -1) return `${agents.trimEnd()}\n\n${block}\n`;
  return `${agents.slice(0, start)}${block}${agents.slice(end + AGENTS_END.length)}`;
};

// The `agentsMd` rules, as { name, order, body }.
const agentsRules = (root) =>
  readdirSync(join(root, SOURCE_DIR))
    .filter((file) => file.endsWith(".mdc"))
    .map((entry) => ({ name: entry.slice(0, -".mdc".length), ...parseRule(readFileSync(join(root, SOURCE_DIR, entry), "utf8")) }))
    .filter((rule) => rule.fields.agentsMd !== undefined)
    .map((rule) => ({ name: rule.name, order: Number(rule.fields.agentsMd), body: rule.body }));

// Every generated file, keyed by its target path.
const expectedFiles = (root) => {
  const files = new Map();
  for (const entry of readdirSync(join(root, SOURCE_DIR)).filter((file) => file.endsWith(".mdc")).toSorted()) {
    const name = entry.slice(0, -".mdc".length);
    const rule = toClaudeRule(name, readFileSync(join(root, SOURCE_DIR, entry), "utf8"));
    if (rule !== null) files.set(join(TARGET_DIR, `${name}.md`), rule);
  }
  return files;
};

// Writes (or, with check, compares) the generated files; returns the paths that were out of date.
export const sync = (root, { check = false } = {}) => {
  const expected = expectedFiles(root);
  const stale = [];
  // Files we generated earlier whose .mdc is gone or became a skill: stale too.
  const targetDir = join(root, TARGET_DIR);
  const existing = existsSync(targetDir) ? readdirSync(targetDir).filter((file) => file.endsWith(".md")) : [];
  for (const file of existing) {
    const path = join(TARGET_DIR, file);
    if (!expected.has(path) && readFileSync(join(root, path), "utf8").includes(MARKER)) {
      stale.push(path);
      if (!check) rmSync(join(root, path));
    }
  }
  // New or changed rules.
  if (!check) mkdirSync(targetDir, { recursive: true });
  for (const [path, content] of expected) {
    const current = existsSync(join(root, path)) ? readFileSync(join(root, path), "utf8") : undefined;
    if (current === content) continue;
    stale.push(path);
    if (!check) writeFileSync(join(root, path), content);
  }
  // AGENTS.md's always-on block, when the repo has `agentsMd` rules.
  const rules = agentsRules(root);
  const agentsPath = join(root, AGENTS_FILE);
  if (rules.length > 0) {
    const current = existsSync(agentsPath) ? readFileSync(agentsPath, "utf8") : "";
    const next = withAgentsBlock(current, rules);
    if (next !== current) {
      stale.push(AGENTS_FILE);
      if (!check) writeFileSync(agentsPath, next);
    }
  }
  return stale;
};

// CLI: `node scripts/sync-claude-rules.mjs [--check]`, from the repo root.
const main = () => {
  const check = process.argv.includes("--check");
  const stale = sync(process.cwd(), { check });
  // Check mode: out of date is a failure, with the one command that fixes it.
  if (check && stale.length > 0) {
    console.error(`✗ .claude/rules or AGENTS.md is out of date with .cursor/rules:\n${stale.map((path) => `  ${path}`).join("\n")}\nRun: pnpm rules:sync`);
    process.exit(1);
  }
  // Write mode: say what changed, or stay quiet.
  if (!check && stale.length > 0) console.log(`rules:sync updated ${stale.join(", ")}`);
};

// Run only as a script, so the test can import the pure parts.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) main();
